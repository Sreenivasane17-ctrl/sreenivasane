
sets1={1,2,3,4,5}
print(sets1)


#add
sets1.add(6)
print(sets1)

#update

list=[10,20,30]
sets1.update(list)
print(sets1)

#remove

sets1.remove(2)
print(sets1)

#discard

sets2={6,7,8}
sets2.discard(7)
print(sets2)

#pop()

sets3={10,20,30}
sets3.pop()
print(sets3)

#clear

sets3.clear()
print(sets3)
